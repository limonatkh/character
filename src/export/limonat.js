/* =====================================================================
 * LIMONAT GAME EXPORT
 *
 * Converts a compiled model into the exact structure Limonat's
 * js/character.js uses for VR.CHARACTERS entries:
 *   { id, name, tagline, model: { legL, legR, body, head, armL, armR },
 *     palette, outline, noOutline, fpArms }
 * with boxes [x, y, z, w, h, d, 'paletteKey'] relative to each part's pivot,
 * in the same px units (VR.CHARACTER_PX = 0.084). The 20 standard joints
 * are merged into Limonat's 6 animated parts (elbows/knees become rigid,
 * because the game animates those 6 parts only).
 * ===================================================================== */
import { JOINTS, LIMONAT_PARTS } from '../core/skeleton.js';
import { OUTLINE_PX, APP_NAME, APP_VERSION, SCHEMA_VERSION } from '../core/constants.js';

const r3 = v => Math.round(v * 1000) / 1000;
const PART_OF = Object.fromEntries(JOINTS.map(j => [j.name, j.limonat]));

export function limonatId(name, id) {
  const slug = String(name || 'character').toLowerCase().normalize('NFKD').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 24);
  return 'cc_' + (slug || (id || 'character').replace(/[^a-z0-9]/gi, '').slice(-8).toLowerCase());
}

/** Build the VR.CHARACTERS definition object. */
export function toLimonatDef(model, { name, id }) {
  const pos = Object.fromEntries(model.joints.map(j => [j.name, j.pos]));
  const parts = {};
  for (const [part, joint] of Object.entries(LIMONAT_PARTS)) parts[part] = { pivot: pos[joint].map(r3), boxes: [] };
  for (const b of model.boxes) {
    const part = PART_OF[b.joint], p = parts[part].pivot;
    parts[part].boxes.push([r3(b.x - p[0]), r3(b.y - p[1]), r3(b.z - p[2]), b.w, b.h, b.d, b.key]);
  }
  const palette = {}, noOutline = [];
  for (const [k, v] of Object.entries(model.palette)) {
    palette[k] = parseInt(v.hex.slice(1), 16);
    if (!v.outline) noOutline.push(k);
  }
  // first-person view: forearm + hand only, moved up to the shoulder pivot (like Mr. Fridge's fpArms)
  const fpArms = {};
  for (const [part, side] of [['armL', 'left'], ['armR', 'right']]) {
    const lift = pos[side + 'UpperArm'][1] - pos[side + 'LowerArm'][1];
    const p = parts[part].pivot;
    fpArms[part] = model.boxes.filter(b => b.joint === side + 'LowerArm' || b.joint === side + 'Hand')
      .map(b => [r3(b.x - p[0]), r3(b.y - p[1] + lift), r3(b.z - p[2]), b.w, b.h, b.d, b.key]);
  }
  return {
    id: limonatId(name, id),
    name: { en: name, ar: name },
    tagline: { en: 'Made with the Character Creator', ar: 'صُنعت في صانع الشخصيات' },
    model: parts,
    palette,
    fpArms,
    outline: OUTLINE_PX,
    noOutline,
  };
}

function fmtBoxes(boxes, indent) {
  return boxes.map(b => indent + '[' + b.slice(0, 6).join(', ') + ", '" + b[6] + "'],").join('\n');
}

/** Drop-in script for the game: registers (or replaces) the character in VR.CHARACTERS. */
export function toLimonatScript(def, meta = {}) {
  const parts = Object.entries(def.model).map(([k, p]) =>
    `      ${k}: {\n        pivot: [${p.pivot.join(', ')}],\n        boxes: [\n${fmtBoxes(p.boxes, '          ')}\n        ],\n      },`).join('\n');
  const fp = Object.entries(def.fpArms).map(([k, b]) => `      ${k}: [\n${fmtBoxes(b, '        ')}\n      ],`).join('\n');
  const pal = Object.entries(def.palette).map(([k, v]) => `      ${k}: 0x${v.toString(16).padStart(6, '0')},`).join('\n');
  return `/* =====================================================================
 * Limonat character: ${meta.name || def.name.en}
 * Generated by ${APP_NAME} ${APP_VERSION} (character schema ${SCHEMA_VERSION})
 * Source character id: ${meta.id || '-'}
 *
 * HOW TO ADD IT TO THE GAME (see LIMONAT_INTEGRATION.md):
 *   1. Copy this file to   js/characters/${def.id}.js
 *   2. In index.html add, right AFTER <script src="js/character.js"></script>:
 *        <script src="js/characters/${def.id}.js"></script>
 *   3. Open the Character menu: "${meta.name || def.name.en}" is in the list.
 * Format = VR.CHARACTERS entry (6 parts, boxes [x, y, z, w, h, d, 'colour'],
 * 1 unit = VR.CHARACTER_PX metres, -Z = front). Do not edit by hand:
 * re-export from the creator instead.
 * ===================================================================== */
(function () {
  if (!window.VR || !Array.isArray(VR.CHARACTERS)) { console.warn('[${def.id}] load this file after js/character.js'); return; }
  const def = {
    id: '${def.id}',
    name: ${JSON.stringify(def.name)},
    tagline: ${JSON.stringify(def.tagline)},
    outline: ${def.outline},
    noOutline: ${JSON.stringify(def.noOutline)},
    palette: {
${pal}
    },
    model: {
${parts}
    },
    fpArms: {
${fp}
    },
  };
  const i = VR.CHARACTERS.findIndex(c => c.id === def.id);
  if (i >= 0) VR.CHARACTERS[i] = def; else VR.CHARACTERS.push(def);
})();
`;
}
