/* =====================================================================
 * Regenerates the files that are DERIVED from the asset registry, so the
 * docs never drift from the assets that really exist:
 *   schema/character.schema.json   JSON Schema (draft 2020-12) with live id enums
 *   schema/asset-catalog.json      machine-readable catalog
 *   docs/ASSET_CATALOG.md          human-readable catalog
 *   docs/AI_PROMPT.txt             the full Image-to-Character prompt
 *   examples/*.json                example documents (validated before writing)
 * Run after adding or changing assets:   npm run gen
 * (The app itself always builds the prompt live, so it is never stale.)
 * ===================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../src/assets/index.js';
import { allAssets, listAssets, listBases, SLOTS, SLOT_IDS } from '../src/core/registry.js';
import { ATTACH_POINTS, ATTACH_POINT_IDS, JOINTS } from '../src/core/skeleton.js';
import { MATERIALS, MATERIAL_IDS, APP_VERSION } from '../src/core/constants.js';
import { SCHEMA_VERSION, PROPORTIONS, PROPORTION_KEYS } from '../src/schema/schema.js';
import { buildPrompt, buildCatalogJson, buildJsonSchema, exampleDocument } from '../src/schema/prompt.js';
import { validateDocument, baseConfig } from '../src/schema/validate.js';
import { newDocument } from '../src/core/document.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const write = (rel, data) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, typeof data === 'string' ? data : JSON.stringify(data, null, 2) + '\n');
  console.log('wrote', rel);
};

// ------------------------------------------------------------------ schema + catalog
write('schema/character.schema.json', buildJsonSchema());
write('schema/asset-catalog.json', buildCatalogJson());
write('docs/AI_PROMPT.txt', buildPrompt({ includeCatalog: true }) + '\n');

// ------------------------------------------------------------------ catalog markdown
const md = [];
md.push(`# Asset catalog`, '', `> Generated by \`npm run gen\` from the asset registry (creator ${APP_VERSION}, schema ${SCHEMA_VERSION}). Do not edit by hand.`, '');
md.push(`${allAssets().length} assets in ${SLOT_IDS.length} slots, ${listBases().length} base characters. Use the ids exactly as written.`, '');
md.push('## Base characters', '', '| id | Name | Description |', '|---|---|---|');
for (const b of listBases()) md.push(`| \`${b.id}\` | ${b.label.en} / ${b.label.ar} | ${b.description} |`);
for (const slot of SLOT_IDS) {
  md.push('', `## ${SLOTS[slot].label.en} (\`${slot}\`)`, '', `Field: \`character.${SLOTS[slot].path}\``, '', '| id | Name | Colours (default) | Notes |', '|---|---|---|---|');
  for (const a of listAssets(slot)) {
    const cols = a.colors.map(c => `${c.key}: ${c.label.en} \`${c.default}\``).join('<br>') || '—';
    const notes = [a.description, a.material ? `material: ${a.material}` : '', a.sides ? `side: ${a.sides.join(' / ')}` : '', a.attach ? `attachTo: ${a.attach.points.join(' / ')} (default ${a.attach.default})` : ''].filter(Boolean).join(' — ');
    md.push(`| \`${a.id}\` | ${a.label.en} / ${a.label.ar} | ${cols} | ${notes.replace(/\|/g, '\\|')} |`);
  }
}
md.push('', '## Attachment points', '', '| id | Joint | Name |', '|---|---|---|');
for (const p of ATTACH_POINT_IDS) md.push(`| \`${p}\` | \`${ATTACH_POINTS[p].joint}\` | ${ATTACH_POINTS[p].label.en} / ${ATTACH_POINTS[p].label.ar} |`);
md.push('', '## Materials', '', '| id | Name | glTF roughness / metalness |', '|---|---|---|');
for (const m of MATERIAL_IDS) md.push(`| \`${m}\` | ${MATERIALS[m].label.en} / ${MATERIALS[m].label.ar} | ${MATERIALS[m].roughness} / ${MATERIALS[m].metalness} |`);
md.push('', '## Proportions', '', '| key | min | max | meaning |', '|---|---|---|---|');
for (const k of PROPORTION_KEYS) md.push(`| \`${k}\` | ${PROPORTIONS[k].min} | ${PROPORTIONS[k].max} | ${PROPORTIONS[k].doc} |`);
md.push('', '## Skeleton', '', '| Joint (VRM name) | Parent | Limonat part |', '|---|---|---|');
for (const j of JOINTS) md.push(`| \`${j.name}\` | ${j.parent ? '`' + j.parent + '`' : '—'} | ${j.limonat} |`);
write('docs/ASSET_CATALOG.md', md.join('\n') + '\n');

// ------------------------------------------------------------------ examples (each validated)
function mustValidate(name, doc) {
  const r = validateDocument(doc);
  if (r.errors.length) throw new Error(`${name} does not validate: ${r.errors.map(e => e.message).join('; ')}`);
  return doc;
}
write('examples/ai-output-example.json', mustValidate('example', exampleDocument()));

