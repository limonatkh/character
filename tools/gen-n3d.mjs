/* =====================================================================
 * Regenerates the Normal 3D files DERIVED from the live registry, so they
 * never drift from what the creator supports:
 *   schema/limonat-character-3d.schema.json   JSON Schema (draft 2020-12)
 *   schema/limonat-3d-asset-catalog.json       machine-readable catalog
 *   docs/N3D_AI_PROMPT.txt                     the full Image-to-Character prompt
 *   docs/N3D_ASSET_CATALOG.md                  human-readable catalog
 *   examples/n3d/*.json                        example documents (validated)
 * Run after adding or changing Normal 3D assets:   npm run gen
 * ===================================================================== */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../src/n3d/assets/index.js';
import { allAssets, listAssets, SLOTS } from '../src/n3d/core/registry.js';
import { BODY_PARAMS, FACE_PARAMS } from '../src/n3d/core/params.js';
import { EYE_PARAMS, SKIN_PARAMS, MAKEUP_PARAMS, BROW_PARAMS, N3D_FORMAT, N3D_VERSION, createN3DDocument } from '../src/n3d/core/document.js';
import { FABRICS, PATTERNS, HARDWARE } from '../src/n3d/materials/fabrics.js';
import { DETAIL_LEVELS } from '../src/n3d/core/detail.js';
import { BONES, ATTACH_POINTS } from '../src/n3d/core/skeleton.js';
import { BODY_PRESETS } from '../src/n3d/assets/presets.js';
import { buildN3DPrompt, buildN3DCatalogJson, buildN3DJsonSchema, exampleN3D, N3D_CATALOG_ORDER } from '../src/n3d/schema/prompt.js';
import { validateN3D, LIMITS } from '../src/n3d/schema/validate.js';
import { APP_VERSION } from '../src/core/constants.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const write = (rel, data) => {
  const p = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, typeof data === 'string' ? data : JSON.stringify(data, null, 2) + '\n');
  console.log('wrote', rel);
};
const esc = s => String(s ?? '').replace(/\|/g, '\\|');
const fmt = v => (Math.abs(v) >= 10 ? String(v) : String(Math.round(v * 1000) / 1000));
const paramCell = p => (p.type === 'enum' ? p.values.map(v => `\`${v}\``).join(' / ') + ` (default \`${p.default}\`)` : p.type === 'bool' ? `true / false (default ${p.default})` : `${fmt(p.min)} … ${fmt(p.max)} (default ${fmt(p.default)})`);

// ------------------------------------------------------------------ schema, catalog, prompt
write('schema/limonat-character-3d.schema.json', buildN3DJsonSchema());
write('schema/limonat-3d-asset-catalog.json', buildN3DCatalogJson());
write('docs/N3D_AI_PROMPT.txt', buildN3DPrompt({ includeCatalog: true }) + '\n');

// ------------------------------------------------------------------ catalog markdown
const md = [];
const nAssets = allAssets().filter(a => N3D_CATALOG_ORDER.includes(a.slot)).length;
md.push('# Normal 3D asset catalog', '', `> Generated by \`npm run gen\` from the Normal 3D registry (creator ${APP_VERSION}, format \`${N3D_FORMAT}\` ${N3D_VERSION}). Do not edit by hand.`, '');
md.push(`${nAssets} assets in ${N3D_CATALOG_ORDER.length} slots, plus ${listAssets('preset').length} character presets. Use the ids exactly as written. Limits: ${LIMITS.outfit} outfit items, ${LIMITS.accessories} accessories, ${LIMITS.scars} scars.`, '');
for (const slot of N3D_CATALOG_ORDER) {
  md.push(`## ${SLOTS[slot].label.en} (\`${slot}\`)`, '', `Field: \`${SLOTS[slot].path}\``, '');
  for (const a of listAssets(slot)) {
    md.push(`### \`${a.id}\` — ${a.label.en} / ${a.label.ar}`, '', esc(a.description), '');
    const params = Object.entries(a.params || {});
    if (params.length) { md.push('| param | values | meaning |', '|---|---|---|'); for (const [k, p] of params) md.push(`| \`${k}\` | ${paramCell(p)} | ${esc(p.doc || p.label.en)} |`); md.push(''); }
    const cols = Object.entries(a.colors || {});
    if (cols.length) md.push('Colours: ' + cols.map(([k, c]) => `\`${k}\` ${c.label.en} (default \`${c.default}\`)`).join(', '), '');
    if (a.fabrics && a.fabrics.length) md.push('Fabrics: ' + a.fabrics.map(f => `\`${f}\``).join(', ') + (a.fabric ? ` (default \`${a.fabric}\`)` : ''), '');
  }
}
md.push('## Character presets (`preset`)', '', '| id | Name | Description |', '|---|---|---|');
for (const a of listAssets('preset')) md.push(`| \`${a.id}\` | ${a.label.en} / ${a.label.ar} | ${esc(a.description)} |`);
md.push('', '## Body presets', '', '| id | Name | Sets |', '|---|---|---|');
for (const [id, p] of Object.entries(BODY_PRESETS)) md.push(`| \`${id}\` | ${p.label.en} / ${p.label.ar} | ${Object.entries(p.body).map(([k, v]) => `${k} ${v}`).join(', ')} |`);
md.push('', '## Fabrics', '', '| id | Name | weave | thickness (mm) | stiffness |', '|---|---|---|---|---|');
for (const [id, f] of Object.entries(FABRICS)) md.push(`| \`${id}\` | ${f.label.en} / ${f.label.ar} | ${f.weave} | ${(f.thickness * 1000).toFixed(1)} | ${f.stiffness} |`);
md.push('', '## Patterns', '', '| id | Name | colours used |', '|---|---|---|');
for (const [id, p] of Object.entries(PATTERNS)) md.push(`| \`${id}\` | ${p.label.en} / ${p.label.ar} | ${p.colors} |`);
md.push('', '## Hardware finishes', '', '| id | Name | metalness / roughness |', '|---|---|---|');
for (const [id, x] of Object.entries(HARDWARE)) md.push(`| \`${id}\` | ${x.label.en} / ${x.label.ar} | ${x.metalness} / ${x.roughness} |`);
md.push('', '## Detail levels', '', '| id | Name | Meaning |', '|---|---|---|');
for (const [id, d] of Object.entries(DETAIL_LEVELS)) md.push(`| \`${id}\` | ${d.label.en} / ${d.label.ar} | ${esc(d.doc)} |`);
const tableMd = (title, tbl) => { md.push('', `## ${title}`, '', '| key | min | max | default | meaning |', '|---|---|---|---|---|'); for (const [k, p] of Object.entries(tbl)) md.push(`| \`${k}\` | ${fmt(p.min)} | ${fmt(p.max)} | ${fmt(p.default)} | ${esc(p.doc)} |`); };
tableMd('Body parameters (`body.*`)', BODY_PARAMS);
tableMd('Face shape parameters (`face.*`)', FACE_PARAMS);
tableMd('Eyes (`face.eyes.*`)', EYE_PARAMS);
tableMd('Brow overrides (`face.brows.params.*`)', BROW_PARAMS);
tableMd('Skin (`skin.*`)', SKIN_PARAMS);
tableMd('Makeup (`face.makeup.*`)', MAKEUP_PARAMS);
md.push('', '## Skeleton (55 bones, VRM 1.0 humanoid names)', '', '| Bone | Parent | Limonat part |', '|---|---|---|');
for (const b of BONES) md.push(`| \`${b.name}\` | ${b.parent ? '`' + b.parent + '`' : '—'} | ${b.limonat || '—'} |`);
md.push('', '## Attachment points (GLB nodes `attach_<id>`)', '', '| id | Bone | Name |', '|---|---|---|');
for (const [id, p] of Object.entries(ATTACH_POINTS)) md.push(`| \`${id}\` | \`${p.bone}\` | ${p.label.en} / ${p.label.ar} |`);
write('docs/N3D_ASSET_CATALOG.md', md.join('\n') + '\n');

// ------------------------------------------------------------------ examples (each validated)
function mustValidate(name, doc, opts) {
  const r = validateN3D(doc, opts);
  if (!r.ok) throw new Error(`${name} does not validate: ${r.errors.map(e => e.path + ' ' + e.message).join('; ')}`);
  return doc;
}
write('examples/n3d/ai-output-example.json', mustValidate('example', exampleN3D()));
for (const a of listAssets('preset')) {
  const doc = { format: N3D_FORMAT, version: N3D_VERSION, mode: 'normal3d', meta: { name: a.label.en, notes: a.description }, ...JSON.parse(JSON.stringify(a.doc)) };
  write(`examples/n3d/preset-${a.id.replace(/^preset_/, '').replace(/_01$/, '').replace(/_0(\d)$/, '-$1')}.json`, mustValidate(a.id, doc));
}
write('examples/n3d/ai-output-changes.json', mustValidate('changes', {
  format: N3D_FORMAT, version: N3D_VERSION, mode: 'normal3d',
  hair: { colors: { root: '#E9D08A', tip: '#F2E2B0' } },
  accessories: [{ assetId: 'glasses_01', params: { style: 'round' }, colors: { main: '#1C1C1C' } }],
}, { mode: 'merge', base: createN3DDocument() }));
write('examples/n3d/invalid-example.json', {
  format: N3D_FORMAT, version: N3D_VERSION, mode: 'normal3d',
  body: { height: 2.4, muscle: 'strong' },
  hair: { styleId: 'hair_spikey_01' },
  outfit: [{ assetId: 'top_hawaiian_99' }, { assetId: 'bottom_jeans_01', params: { fit: 'baggy' }, colors: { main: 'blue' } }],
});
